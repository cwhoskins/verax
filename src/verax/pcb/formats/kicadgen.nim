proc renderCurve(c: Curve, layerName: string): string =
  ## One top-level `gr_line`/`gr_arc` for one curve of a `shStroke` shape.
  ## `pcb/assemble.buildOutline` is the only producer of `PcbLayer.shapes` in
  ## a freshly assembled board (the four `Edge.Cuts` segments), so a
  ## straight segment is the only shape this needs to render correctly for
  ## `kicad-cli pcb drc` to see a real board outline instead of
  ## `[invalid_outline]` -- "no edges found on Edge.Cuts layer", the failure
  ## this proc exists to prevent. `cvArc` is handled too, for whatever a
  ## future caller adds to `PcbLayer.shapes` directly.
  case c.kind
  of cvSeg:
    "(gr_line (start " & formatMm(c.a.x) & " " & formatMm(-c.a.y) &
      ") (end " & formatMm(c.b.x) & " " & formatMm(-c.b.y) &
      ") (stroke (width 0.1) (type solid)) (layer " &
      escapeKicadString(layerName) & "))"
  of cvArc:
    let s = startPoint(c)
    let e = endPoint(c)
    let m = pointOnArc(c, c.startAngle + c.sweep * 0.5)
    "(gr_arc (start " & formatMm(s.x) & " " & formatMm(-s.y) &
      ") (mid " & formatMm(m.x) & " " & formatMm(-m.y) &
      ") (end " & formatMm(e.x) & " " & formatMm(-e.y) &
      ") (stroke (width 0.1) (type solid)) (layer " &
      escapeKicadString(layerName) & "))"

proc renderGraphics(pcb: Pcb): string =
  for _, l in pcb.layers:
    for shp in l.shapes:
      case shp.kind
      of shStroke:
        for c in shp.path.curves:
          result &= "\t" & renderCurve(c, l.name) & "\n"
      of shFill:
        var pts: seq[string]
        for c in shp.poly.outer.curves:
          let p0 = startPoint(c)
          pts.add "(xy " & formatMm(p0.x) & " " & formatMm(-p0.y) & ")"
        result &= "\t(gr_poly (pts " & pts.join(" ") &
          ") (stroke (width 0.1) (type solid)) (fill yes) (layer " &
          escapeKicadString(l.name) & "))\n"
      of shPad, shText:
        discard   # not produced on a top-level layer by `pcb/assemble.nim`

proc netCodes(pcb: Pcb): Table[string, int] =
  ## Every net that actually carries copper, numbered from 1 in name order
  ## so a re-run of `assemble` + `writeBoard` on an unchanged netlist emits
  ## byte-identical net declarations.
  var names: seq[string]
  for name in pcb.netCopper.keys: names.add name
  names.sort()
  for i, name in names: result[name] = i + 1

