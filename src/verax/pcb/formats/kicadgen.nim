## From-scratch `.kicad_pcb` text synthesis: the other half of what makes
## `formats/kicad.writePcb`'s documented capability boundary -- "do not
## create or reshape a component" -- liftable for a board that never had a
## KiCad source at all (`pcb.source == nil`), which is what
## `pcb/assemble.nim` hands it.
##
## **Produces text, nothing else.** This module needs only `types`/
## `geometry`/`kicadfmt`/`../footprint`, and `kicad.nim` imports it, never
## the reverse -- the board writer is one format-level concern
## (`checkRefusals`'s edit/refuse table for an *existing* board) plus a
## second, this one (author a *new* board), not two writers that both know
## about `Pcb.source`/`KicadDoc`.
##
## **Every `(footprint ...)` node is spliced, not regenerated by rule.**
## `pcb/footprint.Footprint.source` holds the library's own verbatim bytes,
## and this module edits exactly four things in a private copy of them,
## through the *same* `sexp.nim` primitives (`markDirty`/`markInserted`) the
## edit path in `kicad.nim` already uses and already has tests for, rather
## than hand-splicing strings: the `(at)` node (inserted -- a library part
## has none), `(layer)` (front/back), the `Reference` property's value, and
## each pad's `(net ...)`. Regenerating KiCad's own courtyard/silkscreen/
## `3d model` syntax by rule is exactly the bet `formats/kicad.nim`'s own doc
## comment already rejected once (`Prettify()` cannot be reproduced), and
## every one of those nodes survives untouched here for the same reason.
##
## **A placement's footprint is re-resolved at render time
## (`findFootprint(p.footprint)`), not carried on `Placement` itself.**
## `Placement`/`Pcb` stay geometry-plus-forward-reference, the documented
## `pcb/CLAUDE.md` shape; re-resolving costs one extra file read per
## placement and avoids a `Footprint`-shaped field (or a second copy of its
## `source` text) that every other reader/writer of `Pcb` would then have to
## know to ignore. `writeBoard` calls `assemble` immediately before this, so
## the same footprint sources registered when placements were built are
## still registered now.
##
## **Net codes are always declared** (`(net N "name")`, never the
## KiCad->=`20251028` name-only shape `kicad.nim`'s `hasNetCodes` flag
## exists to read) -- the simpler, universally-understood form, and correct
## since nothing here is reading an existing board's own convention back.

